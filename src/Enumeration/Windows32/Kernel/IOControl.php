namespace Clover\Enumeration\Windows32\Kernel;

enum IOControl : int
{
    // ATA pass-through family
    case IOCTL_ATA_PASS_THROUGH = 0x0004D02C;
    case IOCTL_ATA_PASS_THROUGH_DIRECT = 0x0004D030;
    case IOCTL_ATA_PASS_THROUGH_EX = 0x0004D03C;
    case IOCTL_ATA_MINIPORT = 0x0004D040;

    // Storage property / media control
    case IOCTL_STORAGE_QUERY_PROPERTY = 0x002D1400;
    case IOCTL_STORAGE_GET_DEVICE_NUMBER = 0x002D1080;
    case IOCTL_STORAGE_GET_HOTPLUG_INFO = 0x002D1100;
    case IOCTL_STORAGE_MEDIA_REMOVAL = 0x002D4800;
    case IOCTL_STORAGE_EJECT_MEDIA = 0x002D4804;
    case IOCTL_STORAGE_LOAD_MEDIA = 0x002D4808;
    case IOCTL_STORAGE_RESERVE = 0x002D4810;
    case IOCTL_STORAGE_RELEASE = 0x002D4814;
    case IOCTL_STORAGE_GET_MEDIA_TYPES_EX = 0x002D0C00;
    case IOCTL_STORAGE_CHECK_VERIFY = 0x002D0C18;
    case IOCTL_STORAGE_CHECK_VERIFY2 = 0x002D0C20;

    // Disk device control
    case IOCTL_DISK_GET_DRIVE_GEOMETRY = 0x00070000;
    case IOCTL_DISK_GET_DRIVE_GEOMETRY_EX = 0x000700A0;
    case IOCTL_DISK_GET_LENGTH_INFO = 0x0007405C;
    case IOCTL_DISK_GET_PARTITION_INFO = 0x00074004;
    case IOCTL_DISK_GET_PARTITION_INFO_EX = 0x00074048;
    case IOCTL_DISK_SET_PARTITION_INFO = 0x00074008;
    case IOCTL_DISK_SET_PARTITION_INFO_EX = 0x0007404C;
    case IOCTL_DISK_IS_WRITABLE = 0x00070024;
    case IOCTL_DISK_UPDATE_PROPERTIES = 0x00070100;
    case IOCTL_DISK_PERFORMANCE = 0x00070020;

    // Volume / filesystem control
    case IOCTL_VOLUME_GET_VOLUME_DISK_EXTENTS = 0x00560000;
    case IOCTL_VOLUME_IS_CLUSTERED = 0x00560004;
    case IOCTL_VOLUME_GET_GPT_ATTRIBUTES = 0x00560008;

    // SMART / device health
    case IOCTL_SCSI_MINIPORT = 0x0004D008;
    case IOCTL_SCSI_PASS_THROUGH = 0x0004D004;
    case IOCTL_SCSI_PASS_THROUGH_DIRECT = 0x0004D014;
    case IOCTL_SCSI_PASS_THROUGH_EXTENDED = 0x0004D050;

    // USB / device enumeration
    case IOCTL_USB_GET_NODE_INFORMATION = 0x220408;
    case IOCTL_USB_GET_NODE_CONNECTION_INFORMATION = 0x220410;
    case IOCTL_USB_GET_DESCRIPTOR_FROM_NODE_CONNECTION = 0x220418;

    // Generic device control helpers
    case IOCTL_STORAGE_MANAGE_DATA_SET_ATTRIBUTES = 0x002D1C04;
    case IOCTL_STORAGE_MANAGE_DATA_SET_ATTRIBUTES_EX = 0x002D1C08;
    case IOCTL_STORAGE_READ_CAPACITY = 0x002D1404;

    // CD / DVD specific
    case IOCTL_CDROM_READ_TOC = 0x00024000;
    case IOCTL_CDROM_GET_DRIVE_GEOMETRY = 0x00024010;
    case IOCTL_CDROM_RAW_READ = 0x0002403E;

    // Tape / removable media
    case IOCTL_TAPE_GET_DRIVE_PARAMETERS = 0x00040000;
    case IOCTL_TAPE_SET_DRIVE_PARAMETERS = 0x00040004;
    case IOCTL_TAPE_GET_MEDIA_PARAMETERS = 0x00040008;

    // Misc / fallback
    case IOCTL_STORAGE_BASE = 0x002D0000;
    case IOCTL_ATA_BASE = 0x0004D000;
}