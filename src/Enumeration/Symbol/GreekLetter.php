namespace Clover\Enumeration;

abstract class GreekLetter
{
    /**
     * First, beginning
     */
    public const ALPHA = 'α';

    /**
     * Second letter
     */
    public const BETA = 'β';

    /**
     * Gamma rays
     */
    public const GAMMA = 'γ';

    /**
     * Triangle shape
     */
    public const DELTA = 'δ';

    /**
     * Small quantity in calculus
     */
    public const EPSILON = 'ε';

    /**
     * Ancient
     */
    public const DIGAMMA = 'ϝ';

    /**
     * Zeta functions
     */
    public const ZETA = 'ζ';

    /**
     * Efficiency in physics
     */
    public const ETA = 'η';

    /**
     * Angle in trigonometry
     */
    public const THETA = 'θ';

    /**
     * Tiny amount
     */
    public const IOTA = 'ι';

    /**
     * Curvature, spring constant
     */
    public const KAPPA = 'κ';

    /**
     * Wavelength
     */
    public const LAMBDA = 'λ';

    /**
     * Micro (μg)
     */
    public const MU = 'μ';

    /**
     * Frequency
     */
    public const NU = 'ν';

    /**
     * Random variable
     */
    public const XI = 'ξ';

    /**
     * Small o
     */
    public const OMICRON = 'ο';

    /**
     * Circle ratio (~3.14)
     */
    public const PI = 'π';

    /**
     * Obsolete letter
     */
    public const QOPPA = 'ϙ';

    /**
     * Obsolete
     */
    public const SAMPI = 'ϟ';

    /**
     * Density in physics
     */
    public const RHO = 'ρ';

    /**
     * Sum operator (∑), total
     */
    public const SIGMA = 'σ';

    /**
     * Used at end of Greek words
     */
    public const FINAL_SIGMA = 'ς';

    /**
     * Time constant in physics
     */
    public const TAU = 'τ';

    /**
     * Used in particle physics
     */
    public const UPSILON = 'υ';

    /**
     * Golden ratio, angle
     */
    public const PHI = 'φ';

    /**
     * Chi-squared (χ²), Christ
     */
    public const CHI = 'χ';

    /**
     * Wavefunction in quantum
     */
    public const PSI = 'ψ';

    /**
     * End, ohm unit (resistance)
     */
    public const OMEGA = 'ω';

    /**
     * Coptic, obsolete Greek numeral
     */
    public const SHO = 'ϡ';

}
