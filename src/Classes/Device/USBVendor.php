    /**
     * Parse a hardware ID string and return vendor and device information.
     *
     * @param string $hardwareId The hardware ID string to parse.
     * 
     * @return array{
     *  company: array{
     *      name: string, 
     *      id: int|float, 
     *      hexid: string
     *  }, 
     *  device: array{
     *      name: string, 
     *      id: int|float, 
     *      hexid: string
     *  }, 
     *  revision: string
     * }|null An associative array with 'company', 'device', and 'revision' keys, or null if parsing fails.
     */
    public static function parseFromHardwareId(string $hardwareId): array|null
    {
        if (preg_match('/VID_?([0-9A-F]{4}).*?PID_?([0-9A-F]{4})(?:.*?REV_?([0-9A-F]{4}))?/i', $hardwareId, $matches)) {
            $vid = strtoupper($matches[1]);
            $pid = strtoupper($matches[2]);
            $revision = strtoupper($matches[3]);

            $vendor = null;
            if (isset(self::$vendors[hexdec($vid)])) {
                $vendor = self::$vendors[hexdec($vid)];
            }

            return [
                'company' => [
                    'name' => $vendor !== null ? ($vendor['Company'] ?? null) : null,
                    'id' => hexdec($vid),
                    'hexid' => $vid
                ],
                'device' => [
                    'name' => $vendor !== null ? ($vendor['Device'][hexdec($pid)] ?? null) : null,
                    'id' => hexdec($pid),
                    'hexid' => $pid
                ],
                'revision' => $revision
            ];
        }

        return null;
    }

